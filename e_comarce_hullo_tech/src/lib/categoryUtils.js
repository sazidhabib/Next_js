/**
 * Normalizes a URL path for comparison (lowercases, removes leading/trailing slashes, strips /categories prefix)
 */
export function normalizePath(path) {
  if (!path) return "";
  return path
    .toLowerCase()
    .replace(/^\/categories/, "")
    .replace(/^\/+/, "")
    .replace(/\/+$/, "");
}

/**
 * Parses menu data from SiteSetting JSON or raw array
 */
export function parseMenuData(menuData) {
  if (!menuData) return staticCategories;
  if (Array.isArray(menuData) && menuData.length > 0) return menuData;
  if (typeof menuData === "string") {
    try {
      const parsed = JSON.parse(menuData);
      return Array.isArray(parsed) && parsed.length > 0 ? parsed : staticCategories;
    } catch {
      return staticCategories;
    }
  }
  return staticCategories;
}

/**
 * Finds a node anywhere in the 3-level category tree
 * @param {Array} menuTree - The tree of categories
 * @param {string} pathOrSlug - URL path, slug, or category identifier
 * @returns {Object|null} { matchedNode, level, parent, grandparent, subCategories, siblings, breadcrumbs }
 */
export function findCategoryHierarchy(menuTree = staticCategories, pathOrSlug = "") {
  if (!pathOrSlug) return null;
  const normalizedTarget = normalizePath(pathOrSlug);
  const targetSlug = normalizedTarget.split("/").pop();

  const categories = parseMenuData(menuTree);

  // Level 1 search
  for (const cat of categories) {
    const catNorm = normalizePath(cat.href);
    const catSlug = catNorm.split("/").pop();

    if (catNorm === normalizedTarget || catSlug === targetSlug || cat.name.toLowerCase() === normalizedTarget) {
      return {
        matchedNode: cat,
        level: 1,
        parent: null,
        grandparent: null,
        subCategories: cat.subCategories || [],
        siblings: categories,
        breadcrumbs: [{ name: cat.name, href: cat.href }],
      };
    }

    // Level 2 search
    if (cat.subCategories && Array.isArray(cat.subCategories)) {
      for (const sub of cat.subCategories) {
        const subNorm = normalizePath(sub.href);
        const subSlug = subNorm.split("/").pop();

        if (subNorm === normalizedTarget || subSlug === targetSlug || sub.name.toLowerCase() === normalizedTarget) {
          return {
            matchedNode: sub,
            level: 2,
            parent: cat,
            grandparent: null,
            subCategories: sub.subCategories || [],
            siblings: cat.subCategories,
            breadcrumbs: [
              { name: cat.name, href: cat.href },
              { name: sub.name, href: sub.href },
            ],
          };
        }

        // Level 3 search
        if (sub.subCategories && Array.isArray(sub.subCategories)) {
          for (const subSub of sub.subCategories) {
            const subSubNorm = normalizePath(subSub.href);
            const subSubSlug = subSubNorm.split("/").pop();

            if (
              subSubNorm === normalizedTarget ||
              subSubSlug === targetSlug ||
              subSub.name.toLowerCase() === normalizedTarget
            ) {
              return {
                matchedNode: subSub,
                level: 3,
                parent: sub,
                grandparent: cat,
                subCategories: [],
                siblings: sub.subCategories,
                breadcrumbs: [
                  { name: cat.name, href: cat.href },
                  { name: sub.name, href: sub.href },
                  { name: subSub.name, href: subSub.href },
                ],
              };
            }
          }
        }
      }
    }
  }

  return null;
}

/**
 * Resolves full breadcrumbs for a product based on its category, subcategory, subSubcategory, and menu hierarchy
 */
export function getProductBreadcrumbs(menuTree = staticCategories, product = {}) {
  const crumbs = [];

  if (!product) return crumbs;

  const categories = parseMenuData(menuTree);

  // 1. Try finding by subSubcategory if present
  let matchedHierarchy = null;
  if (product.subSubcategory) {
    matchedHierarchy = findCategoryHierarchy(categories, product.subSubcategory);
  }

  // 2. If not found, try subcategory
  if (!matchedHierarchy && product.subcategory) {
    matchedHierarchy = findCategoryHierarchy(categories, product.subcategory);
  }

  // 3. If not found, try category
  if (!matchedHierarchy && product.category) {
    matchedHierarchy = findCategoryHierarchy(categories, product.category);
  }

  if (matchedHierarchy && matchedHierarchy.breadcrumbs) {
    crumbs.push(...matchedHierarchy.breadcrumbs);
  } else {
    // Fallback breadcrumbs if hierarchy lookup did not find matches
    if (product.category) {
      const catDisplayName = product.category.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
      crumbs.push({ name: catDisplayName, href: `/${product.category}` });
    }
    if (product.subcategory) {
      const subDisplayName = product.subcategory.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
      crumbs.push({ name: subDisplayName, href: `/${product.category}/${product.subcategory}` });
    }
    if (product.subSubcategory) {
      const subSubDisplayName = product.subSubcategory.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
      crumbs.push({ name: subSubDisplayName, href: `/${product.category}/${product.subcategory}/${product.subSubcategory}` });
    }
  }

  return crumbs;
}
